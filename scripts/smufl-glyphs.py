"""
Regenerates src/lib/music/score/glyphs.ts: the SMuFL music symbols used by the
score view, as SVG path data (staff spaces, y axis down, SMuFL origins).

Source: Bravura (SIL Open Font License 1.1, Reserved Font Name "Bravura").
The licence ships at public/licenses/bravura-OFL.txt and must stay there.

  python3 -m venv .venv-glyphs && .venv-glyphs/bin/pip install fonttools
  curl -LO https://raw.githubusercontent.com/steinbergmedia/bravura/master/redist/otf/Bravura.otf
  curl -LO https://raw.githubusercontent.com/steinbergmedia/bravura/master/redist/Bravura.json
  curl -LO https://raw.githubusercontent.com/w3c/smufl/gh-pages/metadata/glyphnames.json
  .venv-glyphs/bin/python scripts/smufl-glyphs.py Bravura.otf Bravura.json glyphnames.json src/lib/music/score/glyphs.ts
"""
import json
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

GLYPHS = [
    "gClef", "gClef8vb", "fClef",
    *[f"timeSig{i}" for i in range(10)], "timeSigCommon", "timeSigCutCommon",
    "noteheadWhole", "noteheadHalf", "noteheadBlack", "augmentationDot",
    "flag8thUp", "flag8thDown", "flag16thUp", "flag16thDown",
    "flag32ndUp", "flag32ndDown", "flag64thUp", "flag64thDown",
    # Arabic-style accidentals (SMuFL U+ED30–ED38): the half-flat is a slashed
    # flat and the half-sharp a single-stroke sharp, as in Arabic scores.
    "accidentalDoubleFlatArabic", "accidentalThreeQuarterTonesFlatArabic", "accidentalFlatArabic",
    "accidentalQuarterToneFlatArabic", "accidentalNaturalArabic", "accidentalQuarterToneSharpArabic",
    "accidentalSharpArabic", "accidentalThreeQuarterTonesSharpArabic", "accidentalDoubleSharpArabic",
    "restWhole", "restHalf", "restQuarter", "rest8th", "rest16th", "rest32nd", "rest64th",
    *[f"tuplet{i}" for i in range(10)],
]

ENGRAVING_KEYS = [
    "staffLineThickness", "stemThickness", "beamThickness", "beamSpacing", "legerLineThickness",
    "legerLineExtension", "thinBarlineThickness", "thickBarlineThickness", "barlineSeparation",
    "thinThickBarlineSeparation", "repeatBarlineDotSeparation", "tieMidpointThickness",
    "tieEndpointThickness", "tupletBracketThickness", "repeatEndingLineThickness",
]


def num(v: float) -> str:
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def main(font_path: str, meta_path: str, names_path: str, out_path: str) -> None:
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    sp = font["head"].unitsPerEm / 4  # SMuFL: 1 em = 4 staff spaces
    meta = json.load(open(meta_path))
    names = json.load(open(names_path))

    rows = []
    for name in GLYPHS:
        glyph = cmap[int(names[name]["codepoint"][2:], 16)]
        pen = SVGPathPen(glyph_set, ntos=num)
        glyph_set[glyph].draw(TransformPen(pen, (1 / sp, 0, 0, -1 / sp, 0, 0)))
        sw, ne = meta["glyphBBoxes"][name]["bBoxSW"], meta["glyphBBoxes"][name]["bBoxNE"]
        bbox = [sw[0], -ne[1], ne[0], -sw[1]]  # [left, top, right, bottom], y down
        width = meta["glyphAdvanceWidths"].get(name, glyph_set[glyph].width / sp)
        rows.append(f'  {name}: {{ w: {num(width)}, bbox: [{", ".join(num(v) for v in bbox)}], d: "{pen.getCommands()}" }},')

    engraving = ", ".join(f"{k}: {meta['engravingDefaults'][k]}" for k in ENGRAVING_KEYS)
    out = f"""/* Generated by scripts/smufl-glyphs.py — do not edit by hand.
 *
 * Music symbols from {meta["fontName"]} {meta["fontVersion"]} (SMuFL), © Steinberg Media Technologies GmbH,
 * licensed under the SIL Open Font License 1.1 (public/licenses/bravura-OFL.txt).
 * Units are staff spaces with the y axis pointing down; origins follow SMuFL
 * (noteheads centred on their line/space, clefs on their reference line). */

export const ENGRAVING = {{ {engraving} }} as const;

export const GLYPHS = {{
{chr(10).join(rows)}
}} as const satisfies Record<string, {{ w: number; bbox: readonly [number, number, number, number]; d: string }}>;

export type GlyphName = keyof typeof GLYPHS;
"""
    open(out_path, "w").write(out)
    print(f"wrote {len(rows)} glyphs to {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:5])
